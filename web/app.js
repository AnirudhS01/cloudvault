// ---- Master passphrase: first time creates salt + check value, afterwards verifies it ----
$("unlock").onsubmit = async (e) => {
  e.preventDefault(); say();
  try {
    const mp = $("mp").value;
    if (meta) {
      const k = await deriveKey(mp, meta.salt);
      try { await decrypt(k, meta.check); } catch { throw new Error("Wrong master passphrase"); }
      key = k;
    } else {
      if (mp.length < 12) throw new Error("Use at least 12 characters");
      if (mp !== $("mp2").value) throw new Error("Passphrases do not match");
      const salt = newSalt(), k = await deriveKey(mp, salt);
      await api("PUT", "/vault/META", JSON.stringify({ salt, check: await encrypt(k, { ok: 1 }) }));
      key = k;
    }
    $("mp").value = $("mp2").value = "";
    entries = await Promise.all(entries.map(async (i) => ({ id: i.id, ...(await decrypt(key, JSON.parse(i.blob))) })));
    $("who").textContent = $("email").value;
    view("vault"); render();
  } catch (x) { if (x.message !== "expired") say(x.message); }
};

// ---- Dashboard ----
// textContent only (never innerHTML): stored data can never inject HTML or script
const el = (tag, cls, text = "") => Object.assign(document.createElement(tag), { className: cls, textContent: text });
const hue = (s) => [...s].reduce((h, c) => (h * 31 + c.charCodeAt(0)) % 360, 7);

function card(v) {
  const box = el("div", "entry"), head = el("div", "head"), meta = el("div", "meta"), acts = el("div", "acts");
  const av = el("div", "avatar", (v.site.trim()[0] || "?").toUpperCase());
  av.style.background = `hsl(${hue(v.site.toLowerCase())} 65% 50%)`;
  const pw = el("code", "", "••••••••••");
  const btn = (label, cls, fn) => Object.assign(el("button", cls, label), { onclick: fn });
  const show = btn("👁 Show", "", () => { const on = pw.textContent.startsWith("•"); pw.textContent = on ? v.pass : "••••••••••"; show.textContent = on ? "🙈 Hide" : "👁 Show"; });
  const copy = btn("📋 Copy", "", async () => { await navigator.clipboard.writeText(v.pass); say("Password copied", true); });
  const del = btn("🗑 Delete", "del", async () => {
    if (!confirm(`Delete ${v.site}?`)) return;
    try { await api("DELETE", "/vault/" + v.id); entries = entries.filter((x) => x.id !== v.id); render(); } catch (x) { say(x.message); }
  });
  meta.append(el("b", "", v.site), el("span", "", v.user)); head.append(av, meta); acts.append(show, copy, del);
  box.append(head, pw, acts);
  return box;
}

function render() {
  const q = $("search").value.toLowerCase();
  const shown = entries.filter((v) => (v.site + v.user).toLowerCase().includes(q)).sort((a, b) => a.site.localeCompare(b.site));
  $("count").textContent = entries.length;
  $("list").replaceChildren(...shown.map(card));
  $("empty").hidden = shown.length > 0;
  $("empty").replaceChildren(entries.length
    ? el("b", "", "No matches")
    : el("b", "", "Your vault is empty"), el("span", "", entries.length ? "Try a different search." : "Click “Add password” to save your first one."));
}
$("search").oninput = render;

