const strength = (p) => Math.min(4, (p.length >= 8) + (p.length >= 12) + (/[a-z]/.test(p) && /[A-Z]/.test(p)) + (/\d/.test(p) && /[^\w\s]/.test(p)));
$("pass").oninput = () => ($("meter").className = "s" + strength($("pass").value));

$("add").onsubmit = async (e) => {
  e.preventDefault();
  const v = { site: $("site").value, user: $("user").value, pass: $("pass").value }, id = "E-" + crypto.randomUUID();
  try {
    await api("PUT", "/vault/" + id, JSON.stringify(await encrypt(key, v))); // plaintext never leaves the browser
    entries.push({ id, ...v }); e.target.reset(); $("pass").type = "password"; $("meter").className = "";
    $("addDlg").close(); render(); say("Saved & encrypted 🔒", true);
  } catch (x) { say(x.message); }
};

$("gen").onclick = () => {
  const cs = "abcdefghijkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789!@#$%^&*", lim = 256 - (256 % cs.length), out = [];
  while (out.length < 20) for (const n of crypto.getRandomValues(new Uint8Array(32))) if (n < lim && out.length < 20) out.push(cs[n % cs.length]); // rejection sampling: no modulo bias
  $("pass").type = "text"; $("pass").value = out.join(""); $("pass").oninput();
};


