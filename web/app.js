let token = null, key = null, meta = null, entries = [];

// ---- Cognito (plain HTTPS JSON API, no SDK) ----
async function idp(target, body) {
  const r = await fetch(`https://cognito-idp.${REGION}.amazonaws.com/`, {
    method: "POST",
    headers: { "content-type": "application/x-amz-json-1.1", "x-amz-target": "AWSCognitoIdentityProviderService." + target },
    body: JSON.stringify({ ClientId: CLIENT_ID, ...body }),
  });
  const j = await r.json();
  if (!r.ok) throw Object.assign(new Error(j.message || j.__type), { type: j.__type });
  return j;
}

// ---- Vault API (JWT-protected) ----
async function api(method, path, body) {
  const r = await fetch(API + path, { method, headers: { authorization: token }, body });
  if (r.status === 401) { signOut("Session expired, sign in again."); throw new Error("expired"); }
  if (!r.ok) throw new Error((await r.json().catch(() => ({}))).error || r.status);
  return r.status === 204 ? null : r.json();
}

function signOut(text = "") {
  token = key = meta = null; entries = [];
  document.querySelectorAll("input").forEach((i) => (i.value = ""));
  $("list").replaceChildren(); $("addDlg").close(); view("auth"); say(text);
}

// ---- Auth forms ----
$("auth").onsubmit = async (e) => {
  e.preventDefault(); say();
  try {
    const r = await idp("InitiateAuth", { AuthFlow: "USER_PASSWORD_AUTH", AuthParameters: { USERNAME: $("email").value, PASSWORD: $("pw").value } });
    token = r.AuthenticationResult.IdToken; $("pw").value = "";
    const items = await api("GET", "/vault");
    meta = items.find((i) => i.id === "META");
    meta &&= JSON.parse(meta.blob);
    entries = items.filter((i) => i.id !== "META");
    $("mp2").hidden = !!meta; $("mp2").required = !meta;
    $("unlockTitle").textContent = meta ? "Unlock vault" : "Create master passphrase";
    $("unlockHelp").textContent = meta ? "Your vault is encrypted with your master passphrase." :
      "This encrypts everything in your browser. AWS never sees it. If you forget it, your data cannot be recovered.";
    view("unlock");
  } catch (x) {
    if (x.type === "UserNotConfirmedException") { view("confirm"); say("Verify your email first.", true); }
    else if (x.message !== "expired") say(x.message);
  }
};

